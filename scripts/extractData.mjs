// ---- 4. 输出 backs.ts ----
const backs = backDefs.map(([key, def]) => ({
  key,
  enName: def.name,
  zhName: zhNames[key].name ?? def.name,
  order: def.order,
  pos: def.pos,
  stake: def.stake,
  omit: def.omit === true,
  config: def.config ?? {},
  text: zhNames[key].text ?? [],
  vars: VARS[key] ?? [],
})).sort((a, b) => a.order - b.order);

const header = `// AUTO-GENERATED by scripts/extractData.mjs — DO NOT EDIT\n// 来源: Code/game.lua P_CENTERS + Code/localization/zh_CN.lua\n`;
const body = `export interface BackDef {\n  key: string;\n  enName: string;\n  zhName: string;\n  order: number;\n  pos: { x: number; y: number };\n  stake: number;\n  omit: boolean;\n  config: Record<string, unknown>;\n  text: string[];\n  vars: (number | string)[];\n}\n\nexport const BACKS: BackDef[] = ${JSON.stringify(backs, null, 2)};\n`;
writeFileSync(resolve(dirname(fileURLToPath(import.meta.url)), '../src/data/backs.ts'), header + body);

const selectable = backs.filter(b => !b.omit);
console.log(`extracted ${backs.length} backs (${selectable.length} selectable):`);
for (const b of backs) console.log(`  ${b.key} #${b.order} ${b.zhName} (${b.enName})${b.omit ? ' [omit]' : ''}`);

