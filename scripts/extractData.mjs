import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const gameLua = readFileSync(resolve(ROOT, 'Code/game.lua'), 'utf8');
const zhLua = readFileSync(resolve(ROOT, 'Code/localization/zh_CN.lua'), 'utf8');

/** 从 src[start]（必须为 '{'）平衡扫描到匹配的 '}'，返回含两侧括号的子串 */
function balancedFrom(src, start) {
  if (src[start] !== '{') throw new Error(`balancedFrom: src[start] 不是 '{'`);
  let depth = 0, i = start;
  while (i < src.length) {
    if (src[i] === '{') depth++;
    else if (src[i] === '}') { depth--; if (depth === 0) break; }
    i++;
  }
  return src.slice(start, i + 1);
}

/** 平衡花括号截取 `key={` 的完整块 */
function extractBlock(src, key) {
  const m = new RegExp(`${key}\\s*=\\s*\\{`).exec(src);
  if (!m) return null;
  return balancedFrom(src, m.index + m[0].length - 1);
}

/** 解析单行 Lua 表字面量（b_* 定义都是单行、仅含字符串/数字/布尔/嵌套表） */
function parseLuaLiteral(src) {
  let pos = 0;
  function skipWs() { while (pos < src.length && /\s/.test(src[pos])) pos++; }
  function parseTable() {
    pos++; // {
    const out = {};
    let arrIdx = 0;
    for (;;) {
      skipWs();
      if (src[pos] === '}') { pos++; return out; }
      // 尝试 key=value；否则按位置元素（数组式表，如 consumables = {'c_fool', 'c_fool'}）
      const km = /^([A-Za-z_]\w*)\s*=/.exec(src.slice(pos));
      if (km) {
        pos += km[0].length;
        skipWs();
        out[km[1]] = parseValue();
      } else {
        arrIdx++;
        out[arrIdx] = parseValue();
      }
      skipWs();
      if (src[pos] === ',') pos++;
    }
  }
  function parseValue() {
    skipWs();
    if (src[pos] === '{') return parseTable();
    if (src[pos] === '"' || src[pos] === "'") {
      const q = src[pos];
      const m = new RegExp(`^${q}((?:[^${q}\\\\]|\\\\.)*)${q}`).exec(src.slice(pos));
      pos += m[0].length;
      return m[1];
    }
    const m = /^(true|false|-?\d+\.?\d*(?:e[-+]?\d+)?)/.exec(src.slice(pos));
    if (!m) throw new Error(`bad value at ${pos}: ${src.slice(pos, pos + 30)}`);
    pos += m[0].length;
    return m[1] === 'true' ? true : m[1] === 'false' ? false : Number(m[1]);
  }
  return parseTable();
}

// ---- 1. game.lua 的 b_* 定义 ----
const backDefs = [];
for (const line of gameLua.split('\n')) {
  const m = /^\s{8}(b_\w+)\s*=\s*\{.+\},?\s*$/.exec(line);
  if (m) backDefs.push([m[1], parseLuaLiteral(line.slice(line.indexOf('{')))]);
}

// ---- 2. zh_CN 的名称与描述 ----
const zhNames = {};
function zhName(key) {
  const block = extractBlock(zhLua, key);
  if (!block) return undefined;
  const m = /name\s*=\s*"((?:[^"\\]|\\.)*)"/.exec(block);
  return m ? m[1] : undefined;
}
function zhText(key) {
  const block = extractBlock(zhLua, key);
  if (!block) return [];
  const tm = /text\s*=\s*\{/.exec(block);
  if (!tm) return [];
  const arrSrc = balancedFrom(block, tm.index + tm[0].length - 1);
  return [...arrSrc.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map(x => x[1]);
}
for (const [key] of backDefs) zhNames[key] = { name: zhName(key), text: zhText(key) };

// ---- 3. 描述占位符 #N# 的替换值 ----
